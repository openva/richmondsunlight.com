<?php

###
# Dashboard Portfolio Modification
#
# PURPOSE
# Allows the modification of settings for a single portfolio.
#
###

# INCLUDES
# Include any files or libraries that are necessary for this specific
# page to function.
include_once '../includes/functions.inc.php';
include_once '../includes/settings.inc.php';
include_once '../includes/photosynthesis.inc.php';

# DECLARATIVE FUNCTIONS
# Run those functions that are necessary prior to loading this specific
# page.
$database = new Database();
$database->connect_mysqli();

# PAGE METADATA
$page_title = 'Photosynthesis » Edit Portfolio';
$site_section = 'photosynthesis';

# ADDITIONAL HTML HEADERS
$html_head = '<link rel="stylesheet" href="/css/photosynthesis.css" />';

# INITIALIZE SESSION
resume_session();

# Grab the user data. Send them to log in if they aren't.
$user = get_user();
if ($user === false) {
    header('Location: /account/login/?return_uri=' . urlencode($_SERVER['REQUEST_URI']));
    exit();
}
$user_id = (int) $user['id'];

# The portfolio, which has to be this user's.
$hash = (string) ($_GET['hash'] ?? '');
$portfolio = Portfolio::find($hash, $user_id);
if ($portfolio === null) {
    header('Location: /photosynthesis/');
    exit;
}

if (isset($_POST['submit'])) {
    $form_data = (isset($_POST['form_data']) && is_array($_POST['form_data'])) ? $_POST['form_data'] : [];
    $form_data += ['public' => 'n', 'notify' => 'none', 'notes' => ''];

    if (!Csrf::valid()) {
        $message = '<div id="messages" class="errors">Sorry: This page was out of date. Please make your changes again.</div>';
    } elseif (trim((string) ($form_data['name'] ?? '')) === '') {
        $message = '<div id="messages" class="errors">
				<ul>
					<li>the name of this portfolio</li>
				</ul>
			</div>';
    } else {
        # A smart portfolio's criteria are changed too, and then it's filled again.
        $criteria = $portfolio['type'] == 'smart' ? Portfolio::criteria($form_data) : null;
        $updated = Portfolio::update($hash, $user_id, $form_data, $criteria);
        if ($updated === null) {
            $message = '<div id="messages" class="errors">Sorry: This portfolio could not be edited.</div>';
        } else {
            if ($updated['type'] == 'smart') {
                populate_smart_portfolio($updated['id']);
            }
            header('Location: /photosynthesis/#' . $updated['hash']);
            exit;
        }
    }
}

# Display any messages generated by operations. If there are none, simply initialize
# the variable.
$page_body = $message ?? '';

# The form shows what's saved: the portfolio's fields, and a smart portfolio's criteria.
$criteria = $portfolio['criteria'] ?? [];
unset($portfolio['criteria']);
$portfolio = array_map('stripslashes_nullsafe', array_merge($criteria, $portfolio));

// DISPLAY THE APPROPRIATE FORM
if ($portfolio['type'] == 'smart') {
    $page_body .= @smart_portfolio_form($portfolio);
} else {
    $page_body .= @portfolio_form($portfolio);
}

// OUTPUT THE PAGE
$page = new Page();
foreach ([
    'page_title',
    'page_body',
    'page_sidebar',
    'site_section',
    'browser_title',
    'html_head',
    'body_tag',
] as $prop) {
    if (isset(${$prop})) {
        $page->{$prop} = ${$prop};
    }
}
$page->process();
